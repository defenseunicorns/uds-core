import { Expose, Sso, UDSPackage } from "../../crd";
import { getFqdn } from "../domain-utils";

/**
 * Returns the matching Authservice SSO entry for an expose entry.
 *
 * Matching uses the first SSO entry with an Authservice selector and a redirect URI
 * whose HTTPS origin matches the expose entry's FQDN. Invalid redirect URIs are ignored.
 */
export function getAuthserviceSso(expose: Expose, ssoEntries: Sso[]): Sso | undefined {
  const fqdnOrigin = "https://" + getFqdn(expose);

  return ssoEntries.find(sso => {
    if (!sso.enableAuthserviceSelector) {
      return false;
    }

    return (sso.redirectUris ?? []).some(uri => {
      try {
        return new URL(uri).origin === fqdnOrigin;
      } catch {
        return false;
      }
    });
  });
}

/**
 * Returns the Keycloak client ID used by an authenticated uptime probe.
 */
export function getProbeClientId(clientId: string): string {
  return clientId + "-probe";
}

/**
 * Enumerates the unique probe client IDs generated by the Package's current spec.
 */
export function getGeneratedProbeClientIds(pkg: UDSPackage): string[] {
  const clientIds = new Set<string>();
  const ssoEntries = pkg.spec?.sso ?? [];

  for (const expose of pkg.spec?.network?.expose ?? []) {
    if (!expose.uptime?.checks?.paths?.length) {
      continue;
    }

    const authserviceSso = getAuthserviceSso(expose, ssoEntries);
    if (authserviceSso) {
      clientIds.add(getProbeClientId(authserviceSso.clientId));
    }
  }

  return Array.from(clientIds);
}
